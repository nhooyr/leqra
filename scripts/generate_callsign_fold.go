//go:build ignore

// Regenerate the client callsign-fold tables from the server's Unicode rules:
// go run scripts/generate_callsign_fold.go
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/binary"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"sort"
	"strings"
	"unicode"
)

type foldData struct {
	ScalarSHA256 string      `json:"scalarSHA256"`
	Unicode      string      `json:"unicode"`
	Ranges       [][4]int    `json:"ranges"`
	Singles      [][2]int    `json:"singles"`
	Cases        [][2]string `json:"cases"`
}

func canonicalScalar(r rune) rune {
	// Keep existing Go 1.23 account distinctions when newer Unicode versions
	// add equivalences. Must agree with src/callsign_fold.go.
	switch r {
	case 0x1FD3, 0x1FE3, 0xFB06:
		return r
	}
	smallest := r
	for folded := unicode.SimpleFold(r); folded != r; folded = unicode.SimpleFold(folded) {
		if folded < smallest {
			smallest = folded
		}
	}
	return unicode.ToLower(smallest)
}
func encoded(v any) string {
	b, err := json.Marshal(v)
	if err != nil {
		panic(err)
	}
	return string(b)
}
func write(path, content string) {
	if err := os.WriteFile(filepath.FromSlash(path), []byte(content), 0644); err != nil {
		panic(err)
	}
}
func main() {
	data := foldData{Unicode: unicode.Version, Ranges: [][4]int{}, Singles: [][2]int{}, Cases: [][2]string{{"Σnow", "σnow"}, {"ςNOW", "σnow"}, {"ß", "ß"}, {"SS", "ss"}, {"ẞ", "ß"}, {"ı", "ı"}, {"i", "i"}, {"İ", "i"}, {"µΜμ", "µµµ"}, {"ſS", "ss"}, {"ﬃ", "ﬃ"}, {"FFI", "ffi"}, {"𐐀𐐨", "𐐨𐐨"}, {"ΐ", "ΐ"}, {"ΐ", "ΐ"}, {"ΰ", "ΰ"}, {"ΰ", "ΰ"}, {"ﬆ", "ﬆ"}, {"ﬅ", "ﬅ"}}}
	var pairs [][2]int
	hash := sha256.New()
	var scalar [8]byte
	for r := rune(0); r <= unicode.MaxRune; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		folded := r
		if unicode.IsLetter(r) || unicode.IsDigit(r) {
			folded = canonicalScalar(r)
		}
		binary.BigEndian.PutUint32(scalar[:4], uint32(r))
		binary.BigEndian.PutUint32(scalar[4:], uint32(folded))
		hash.Write(scalar[:])
		if folded != r {
			pairs = append(pairs, [2]int{int(r), int(folded)})
		}
	}
	data.ScalarSHA256 = fmt.Sprintf("%x", hash.Sum(nil))
	sort.Slice(pairs, func(i, j int) bool { return pairs[i][0] < pairs[j][0] })
	for i := 0; i < len(pairs); {
		bestStep, bestCount := 0, 0
		for _, step := range []int{1, 2} {
			count := 1
			for i+count < len(pairs) && pairs[i+count][0] == pairs[i][0]+count*step && pairs[i+count][1]-pairs[i+count][0] == pairs[i][1]-pairs[i][0] {
				count++
			}
			if count > bestCount {
				bestStep, bestCount = step, count
			}
		}
		if bestCount >= 3 {
			data.Ranges = append(data.Ranges, [4]int{pairs[i][0], pairs[i+bestCount-1][0], bestStep, pairs[i][1] - pairs[i][0]})
			i += bestCount
		} else {
			data.Singles = append(data.Singles, pairs[i])
			i++
		}
	}
	raw, _ := json.MarshalIndent(data, "", "  ")
	write("src/tests/fixtures/callsign-fold.json", string(raw)+"\n")
	const begin = "// BEGIN GENERATED CALLSIGN FOLD\n"
	const end = "// END GENERATED CALLSIGN FOLD\n"
	js := begin + "// Generated by scripts/generate_callsign_fold.go (Unicode " + unicode.Version + ", stable Go 1.23 policy).\n" +
		"const callsignFoldRanges=" + encoded(data.Ranges) + ",callsignFoldSingles=new Map(" + encoded(data.Singles) + ");\n" +
		"function canonical(value){\n let result='';for(const char of String(value)){const point=char.codePointAt(0);let folded=callsignFoldSingles.get(point);if(folded===undefined){let low=0,high=callsignFoldRanges.length;while(low<high){const mid=(low+high)>>>1;if(callsignFoldRanges[mid][0]<=point)low=mid+1;else high=mid;}const range=callsignFoldRanges[low-1];folded=range&&point<=range[1]&&(point-range[0])%range[2]===0?point+range[3]:point;}result+=String.fromCodePoint(folded);}return result;\n}\n" + end
	shell, err := os.ReadFile("src/web/index.html")
	if err != nil {
		panic(err)
	}
	match := regexp.MustCompile(`src="(assets/v[^"/]+/callsigns\.js)"`).FindSubmatch(shell)
	if len(match) != 2 {
		panic("index.html must reference versioned callsigns.js")
	}
	path := filepath.Join("src/web", string(match[1]))
	source, err := os.ReadFile(path)
	if err != nil {
		panic(err)
	}
	if start := bytes.Index(source, []byte(begin)); start >= 0 {
		tail := bytes.Index(source[start:], []byte(end))
		if tail < 0 {
			panic("missing generated table end")
		}
		source = append(append(append([]byte{}, source[:start]...), []byte(js)...), source[start+tail+len(end):]...)
	} else {
		source = bytes.Replace(source, []byte("'use strict';\n"), []byte("'use strict';\n"+js), 1)
	}
	write(path, string(source))
	header := "// Generated by scripts/generate_callsign_fold.go (Unicode " + unicode.Version + ", stable Go 1.23 policy).\n// Call after the platform's callsign cleanup; this performs scalar folding only.\n"
	var swift strings.Builder
	swift.WriteString(header + "public enum CallsignCaseFold {\n    private static let ranges: [[Int]] = " + encoded(data.Ranges) + "\n    private static let singles: [UInt32: UInt32] = [")
	for i, p := range data.Singles {
		if i > 0 {
			swift.WriteString(",")
		}
		fmt.Fprintf(&swift, "%d:%d", p[0], p[1])
	}
	swift.WriteString("]\n    public static func fold(_ value: String) -> String {\n        var result = String.UnicodeScalarView()\n        for scalar in value.unicodeScalars {\n            let point = Int(scalar.value)\n            var folded = singles[scalar.value]\n            if folded == nil {\n                var low = 0, high = ranges.count\n                while low < high {\n                    let middle = (low + high) / 2\n                    if ranges[middle][0] <= point { low = middle + 1 } else { high = middle }\n                }\n                if low > 0 {\n                    let range = ranges[low - 1]\n                    if point <= range[1] && (point - range[0]) % range[2] == 0 { folded = UInt32(point + range[3]) }\n                }\n            }\n            result.append(Unicode.Scalar(folded ?? scalar.value)!)\n        }\n        return String(result)\n    }\n}\n")
	write("ios/Sources/leqraCore/CallsignCaseFold.swift", swift.String())
	var kt strings.Builder
	kt.WriteString(header + "package com.leqra.core\n\nobject CallsignCaseFold {\n    private val ranges = arrayOf(\n")
	for _, r := range data.Ranges {
		fmt.Fprintf(&kt, "        intArrayOf(%d,%d,%d,%d),\n", r[0], r[1], r[2], r[3])
	}
	kt.WriteString("    )\n    private val singles = mapOf(\n")
	for _, p := range data.Singles {
		fmt.Fprintf(&kt, "        %d to %d,\n", p[0], p[1])
	}
	kt.WriteString("    )\n    fun fold(value: String): String = buildString {\n        var index = 0\n        while (index < value.length) {\n            val point = value.codePointAt(index)\n            index += Character.charCount(point)\n            var folded = singles[point]\n            if (folded == null) {\n                var low = 0\n                var high = ranges.size\n                while (low < high) {\n                    val middle = (low + high) / 2\n                    if (ranges[middle][0] <= point) low = middle + 1 else high = middle\n                }\n                if (low > 0) {\n                    val range = ranges[low - 1]\n                    if (point <= range[1] && (point - range[0]) % range[2] == 0) folded = point + range[3]\n                }\n            }\n            appendCodePoint(folded ?: point)\n        }\n    }\n}\n")
	write("android/core/src/main/kotlin/com/leqra/core/CallsignCaseFold.kt", kt.String())
	fmt.Printf("Unicode %s: %d changed scalars in %d ranges and %d single mappings\n", data.Unicode, len(pairs), len(data.Ranges), len(data.Singles))
}
