#!/bin/sh
set -eu

script_dir=$(CDPATH= cd "$(dirname "$0")" && pwd)
version=$("$script_dir/version.sh")
if ! awk -v version="$version" 'BEGIN { exit version !~ /^[0-9]+\.[0-9]+\.[0-9]+$/ }'; then
    echo "Invalid iOS release version from scripts/version.sh: $version" >&2
    exit 1
fi

case "${1:-}" in
    --swift)
        [ "$#" -eq 2 ] || exit 2
        output=$2
        mkdir -p "$(dirname "$output")"
        source="// Generated by scripts/ios-version.sh. Do not edit.
enum GeneratedVersion {
    static let value = \"$version\"
}"
        if ! printf '%s\n' "$source" | cmp -s - "$output"; then
            printf '%s\n' "$source" > "$output"
        fi
        ;;
    --plist)
        [ "$#" -eq 3 ] || exit 2
        template=$2
        output=$3
        mkdir -p "$(dirname "$output")"
        cp "$template" "$output"
        /usr/libexec/PlistBuddy -c "Set :CFBundleShortVersionString $version" "$output"
        ;;
    *)
        echo "Usage: $0 --swift OUTPUT | --plist TEMPLATE OUTPUT" >&2
        exit 2
        ;;
esac
